export const categoryCapabilities = (category) => (
    category.groups?.length
        ? category.groups.flatMap((group) => group.items)
        : category.capabilities
);

export const findDivision = (id) => serviceCatalogue.find((division) => division.id === id);

export const findCategory = (divisionId, categoryId) => {
    const division = findDivision(divisionId);
    const category = division?.categories.find((item) => item.id === categoryId);
    return division && category ? { division, category } : null;
};

export const allCategories = () => serviceCatalogue.flatMap((division) => (
    division.categories.map((category) => ({
        ...category,
        divisionId: division.id,
        divisionTitle: division.title,
        path: `/services/${division.id}/${category.id}`,
        capabilities: categoryCapabilities(category),
    }))
));
